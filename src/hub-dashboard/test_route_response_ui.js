'use strict';
const assert = require('node:assert/strict');
const {readFileSync} = require('node:fs');
const vm = require('node:vm');
const source = readFileSync(__dirname + '/static/app.js','utf8');
const ids = ['route-task-input','route-studio-mode','route-task-id-input','route-studio-error',
  'route-studio-results','route-studio-loading','route-studio-loading-text','route-context-constraints',
  'route-context-loaded_skill_ids_and_versions'];
const elements=Object.fromEntries(ids.map(id=>[id,{value:'',hidden:true}]));
elements['route-studio-mode'].value='tempr';
const pending=[], rendered=[];
const ctx=vm.createContext({document:{getElementById:id=>elements[id]},rendered,
  apiFetch:(path, options)=>new Promise((resolve,reject)=>pending.push({path,options,resolve,reject}))});
vm.runInContext(source.slice(source.indexOf('function routeText('),source.indexOf('async function loadRoutingView('))+
  '\nrenderRouteChoicePool=()=>{};renderRouteTaskStudioResults=d=>rendered.push(d.outcome);renderSemanticStudioResults=d=>rendered.push(d.status);',ctx);
