const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const source = fs.readFileSync(__dirname + '/static/app.js', 'utf8');
const elements = Object.fromEntries(['route-task-input','route-studio-mode','route-task-id-input','route-studio-error','route-studio-results','route-studio-loading','route-studio-loading-text'].map(id => [id, {value: '', hidden: true}]));
elements['route-studio-mode'].value = 'tempr';
const pending = [], rendered = [];
const ctx = vm.createContext({document:{getElementById:id=>elements[id]},apiFetch:()=>new Promise((resolve,reject)=>pending.push({resolve,reject})),renderRouteTaskStudioResults:d=>rendered.push(d.outcome)});
const start = source.indexOf('const routeContextFields');
vm.runInContext(source.slice(start, source.indexOf('\nfunction renderRouteTaskStudioResults',start)),ctx);
(async()=>{
  elements['route-task-input'].value='A'; const a=ctx.runRouteTaskStudio();
  elements['route-task-input'].value='B'; const b=ctx.runRouteTaskStudio();
  pending[1].resolve({data:{outcome:'SELECTED'}}); await b;
  pending[0].resolve({data:{outcome:'ABSTAIN_LOW_CONFIDENCE'}}); await a;
  assert.deepEqual(rendered,['SELECTED']);
  const c=ctx.runRouteTaskStudio(); elements['route-studio-mode'].value='semantic';
  pending[2].resolve({data:{outcome:'ABSTAIN_LOW_CONFIDENCE'}}); await c;
  assert.deepEqual(rendered,['SELECTED']);
  elements['route-studio-mode'].value='tempr'; const d=ctx.runRouteTaskStudio();
  elements['route-task-input'].value='changed'; pending[3].reject(new Error('old error')); await d;
  assert.equal(elements['route-studio-error'].hidden,true);
  elements['route-task-input'].value='clear pending'; const clearing=ctx.runRouteTaskStudio();
  const clearHandler="btnClearRoute.addEventListener('click', () => {";
  const clearStart=source.indexOf(clearHandler)+clearHandler.length;
  vm.runInContext('{' + source.slice(clearStart,source.indexOf('\n    });',clearStart)) + '}',ctx);
  assert.equal(elements['route-task-input'].value,'');
  assert.equal(elements['route-studio-loading'].hidden,true);
  pending[4].resolve({data:{outcome:'ABSTAIN_LOW_CONFIDENCE'}}); await clearing;
  assert.deepEqual(rendered,['SELECTED']);
  // Exercise the actual decision expression rather than imposing a synthetic default.
  const expression=source.match(/const outcomeRaw = ([^;]+);/)[1];
  assert.equal(vm.runInNewContext(expression,{data:{}}),'UNKNOWN');
  assert.equal(vm.runInNewContext(expression,{data:{outcome:'ABSTAIN_LOW_CONFIDENCE'}}),'ABSTAIN_LOW_CONFIDENCE');
  elements['route-context-constraints']={value:'không xóa\nGiữ 😀'};
  assert.equal(JSON.stringify(ctx.readRouteContext()), JSON.stringify({constraints:['không xóa','Giữ 😀']}));
  elements['route-task-input'].value='context change'; const changing=ctx.runRouteTaskStudio();
  elements['route-context-constraints'].value='new';
  pending[5].resolve({data:{outcome:'ABSTAIN_LOW_CONFIDENCE'}}); await changing;
  assert.deepEqual(rendered,['SELECTED']);
  elements['route-context-loaded_skill_ids_and_versions']={value:'[]'};
  assert.equal(JSON.stringify(ctx.readRouteContext().loaded_skill_ids_and_versions),'[]');
  elements['route-context-loaded_skill_ids_and_versions'].value='null';
  assert.equal(ctx.readRouteContext().loaded_skill_ids_and_versions,null);
  elements['route-context-loaded_skill_ids_and_versions'].value='{bad';
  await ctx.runRouteTaskStudio(); assert.equal(pending.length,6);
  assert.equal(elements['route-studio-error'].hidden,false);
  vm.runInContext('{' + source.slice(clearStart,source.indexOf('\n    });',clearStart)) + '}',ctx);
  assert.equal(elements['route-context-constraints'].value,'');
  assert.equal(ctx.readRouteContext(),null);
  console.log('Response order/query/mode/error and missing outcome PASS');
})().catch(e=>{console.error(e);process.exitCode=1;});
